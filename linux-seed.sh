#!/bin/bash
# Скрипт для быстрого запуска сид-ноды Primus

# 1. Задаем порт (по умолчанию 9000, если не передан аргументом)
export PRIMUS_PORT=${1:-9000}

# 2. Включаем логирование, чтобы видеть подключения
export RUST_LOG=info

# 3. Задаем папку для ключей и DHT, чтобы они хранились рядом со скриптом
export PRIMUS_CONFIG_DIR="./primus-seed-data"

# Проверяем и создаем папку, если ее нет
mkdir -p "$PRIMUS_CONFIG_DIR"

echo "=========================================================="
echo "🚀 Запуск сид-ноды Primus..."
echo "📡 Порт: $PRIMUS_PORT (убедитесь, что UDP открыт в фаерволе)"
echo "📁 Данные сохраняются в: $PRIMUS_CONFIG_DIR"
echo "=========================================================="

# 4. Собираем и запускаем демона в релизном профиле для максимальной скорости
cargo run --release --bin messenger
